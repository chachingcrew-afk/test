"""Turn the KidsDeco competitor Excel into a product list for the tracker.

    python scripts/import_excel.py KidsDeco_100_termek_versenytarsak.xlsx [--ean-only]

--ean-only keeps only competitors whose EAN matches ours ("Azonos EAN"), and only
the KidsDeco products that have at least one such competitor.

Writes config/products/kidsdeco.yaml with
- every KidsDeco product (role: own), so we can compare our price with theirs
- every competitor row that has a URL (role: competitor)
IDs are stable (KidsDeco ID + match number), so re-importing an updated Excel
keeps the price history of unchanged rows.
"""
import re
import sys
from pathlib import Path
from urllib.parse import urlparse

import openpyxl
import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "config" / "products" / "kidsdeco.yaml"

OWN_SHEET = "100 kiválasztott termék"
COMPETITOR_SHEET = "Versenytárstalálatok"

# only used when the page itself does not state a currency
EUROZONE_TLDS = {"nl", "be", "de", "fr", "at", "es", "it", "ie", "fi", "pt", "lu", "sk", "si", "ee", "lv", "lt",
                 "gr", "cy", "mt", "hr"}
EAN_MATCH = "Azonos EAN"
TLD_CURRENCY = {**{tld: "EUR" for tld in EUROZONE_TLDS}, "no": "NOK", "ch": "CHF", "se": "SEK", "dk": "DKK", "uk": "GBP", "pl": "PLN",
                "cz": "CZK", "hu": "HUF", "us": "USD", "au": "AUD", "ca": "CAD"}


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:40]


def tld_currency(url: str) -> str | None:
    return TLD_CURRENCY.get(urlparse(url).netloc.rsplit(".", 1)[-1].lower())


def header_index(ws, header_row_values) -> tuple[int, dict]:
    """Find the header row (starts with 'ID') and map column names to positions."""
    for row in ws.iter_rows(min_row=1, max_row=30):
        values = [c.value for c in row]
        if values and values[0] == "ID":
            return row[0].row, {str(v).strip(): i for i, v in enumerate(values) if v}
    raise ValueError(f"no header row in sheet {ws.title}")


def cell_url(cell) -> str | None:
    if cell.hyperlink and cell.hyperlink.target:
        return cell.hyperlink.target
    value = cell.value
    return value if isinstance(value, str) and value.startswith("http") else None


def main() -> None:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    ean_only = "--ean-only" in sys.argv
    xlsx = Path(args[0])
    wb = openpyxl.load_workbook(xlsx)
    products = []

    ws = wb[OWN_SHEET]
    start, col = header_index(ws, None)
    for row in ws.iter_rows(min_row=start + 1):
        kd_id = row[col["ID"]].value
        url = cell_url(row[col["KidsDeco URL"]])
        if not isinstance(kd_id, int) or not url:
            continue
        products.append({
            "id": f"kd-{kd_id:03d}-kidsdeco",
            "name": row[col["KidsDeco terméknév"]].value,
            "url": url,
            "currency": "EUR",
            "kidsdeco_id": kd_id,
            "role": "own",
            "shop": "kidsdeco.nl",
        })

    ws = wb[COMPETITOR_SHEET]
    start, col = header_index(ws, None)
    for row in ws.iter_rows(min_row=start + 1):
        kd_id = row[col["ID"]].value
        url = cell_url(row[col["Konkurens URL"]])
        if not isinstance(kd_id, int) or not url:
            continue
        if ean_only and row[col["Egyezés minősége"]].value != EAN_MATCH:
            continue
        shop = row[col["Konkurens webshop"]].value or urlparse(url).netloc
        n = row[col["Találat sorszáma"]].value
        item = {
            "id": f"kd-{kd_id:03d}-c{int(n):02d}-{slug(shop)}",
            "name": row[col["Konkurens terméknév"]].value,
            "url": url,
            "kidsdeco_id": kd_id,
            "role": "competitor",
            "shop": shop,
            "match": row[col["Egyezés minősége"]].value,
        }
        currency = tld_currency(url)
        if currency:
            item["currency"] = currency
        products.append(item)

    if ean_only:
        with_competitor = {p["kidsdeco_id"] for p in products if p["role"] == "competitor"}
        products = [p for p in products if p["role"] == "competitor" or p["kidsdeco_id"] in with_competitor]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    header = (f"# Generated by scripts/import_excel.py from {xlsx.name}"
              f"{' (--ean-only)' if ean_only else ''}. Do not edit by hand,\n"
              f"# re-run the import instead. {len(products)} products.\n")
    OUT.write_text(header + yaml.safe_dump({"products": products}, allow_unicode=True, sort_keys=False,
                                           width=200), encoding="utf-8")
    own = sum(p["role"] == "own" for p in products)
    print(f"wrote {OUT.relative_to(ROOT)}: {own} KidsDeco + {len(products) - own} competitor URLs")


if __name__ == "__main__":
    main()
