-- (already applied to the price-tracker project)

create table if not exists public.product_prices (
  id bigint generated by default as identity primary key,
  name text not null,
  ean text,
  url text not null,
  price numeric,
  currency text default 'EUR',
  status text not null,          -- 'ok' | 'error' | 'not_found'
  error text,
  raw_text text,
  scraped_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  domain text,
  match_type text                -- 'ean' | 'name' | 'manual'
);
create index if not exists product_prices_ean_idx        on public.product_prices (ean);
create index if not exists product_prices_scraped_at_idx on public.product_prices (scraped_at desc);
create index if not exists product_prices_status_idx     on public.product_prices (status);
create index if not exists product_prices_domain_idx     on public.product_prices (domain);
alter table public.product_prices enable row level security;

-- Where each product was found on each competitor site (url null = not sold there)
create table if not exists public.competitor_urls (
  product_key  text not null,
  domain       text not null,
  product_name text,
  url          text,
  match_type   text,
  match_score  numeric,
  checked_at   timestamptz not null default now(),
  primary key (product_key, domain)
);
alter table public.competitor_urls enable row level security;

-- Which site search works on each competitor
create table if not exists public.competitor_sites (
  domain          text primary key,
  search_method   text,
  search_template text,
  updated_at      timestamptz not null default now()
);
alter table public.competitor_sites enable row level security;

create or replace view public.latest_prices
with (security_invoker = true) as
select distinct on (url)
  name, ean, url, price, currency, raw_text, scraped_at, domain, match_type
from public.product_prices
where status = 'ok'
order by url, scraped_at desc;
