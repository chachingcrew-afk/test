-- Run once in Supabase: SQL Editor > New query > Run

create table if not exists public.product_prices (
  id bigint generated by default as identity primary key,
  name text not null,
  ean text,
  url text not null,
  price numeric,
  currency text default 'EUR',
  status text not null,          -- 'ok' or 'error'
  error text,
  raw_text text,
  scraped_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create index if not exists product_prices_ean_idx        on public.product_prices (ean);
create index if not exists product_prices_scraped_at_idx on public.product_prices (scraped_at desc);
create index if not exists product_prices_status_idx     on public.product_prices (status);

-- RLS on, no public policies: only the service_role key (GitHub secret) can read/write
alter table public.product_prices enable row level security;

-- Latest successful price per URL
create or replace view public.latest_prices
with (security_invoker = true) as
select distinct on (url)
  name, ean, url, price, currency, raw_text, scraped_at
from public.product_prices
where status = 'ok'
order by url, scraped_at desc;
